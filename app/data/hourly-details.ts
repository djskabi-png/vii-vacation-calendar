import type { DiscoveryItem } from "./world-data";

export type HourlyDetails = {
  about: string[];
  stayOptions: { title: string; description: string }[];
  amenities: string[];
  arrivalNotes: string[];
  faq: { question: string; answer: string }[];
};

export function getHourlyDetails(item: DiscoveryItem): HourlyDetails {
  const placeName = item.name;
  const location = item.location;
  return {
    about: [
      `${placeName} הוא מקום אירוח ב${location} שמאפשר לבדוק שהייה קצרה לפי שעה, בהתאם לזמינות. כל הפרטים המוצגים כאן מרוכזים בעמוד אחד כדי שאפשר יהיה להבין את סוג המקום לפני ששולחים בקשה.`,
      `${item.description} המחיר, משך השהייה, החדר הזמין ושעת הכניסה מאושרים מחדש בזמן בדיקת הזמינות, כך שאין הפתעות בתהליך ההזמנה.`,
    ],
    stayOptions: [
      { title: "שהייה קצרה", description: "בוחרים את משך השהייה הרצוי ושולחים בקשה עם שעה מועדפת. הצוות מאשר את החדר, המחיר ושעת הכניסה." },
      { title: "שהייה ארוכה יותר", description: "כאשר המקום מציע זאת, אפשר לבקש מספר שעות נוסף או לינה. האפשרויות מוצגות רק לאחר בדיקת זמינות עדכנית." },
    ],
    amenities: item.features,
    arrivalNotes: [
      "הכתובת המדויקת והנחיות הכניסה נמסרות לאחר אישור ההזמנה.",
      "מומלץ לציין מראש שעה רצויה, משך שהייה וכל בקשה מיוחדת.",
      "התמונות מתארות את המקום, אך החדר הספציפי נקבע לפי המלאי הזמין בעת האישור.",
      "מדיניות ביטול, תשלום ואיחור מוצגת לפני סגירת ההזמנה.",
    ],
    faq: [
      { question: "איך יודעים אם יש חדר פנוי?", answer: "שולחים בקשת זמינות עם העיר והשעה המבוקשת. תשובה סופית מתקבלת רק לאחר שהמקום מאשר את החדר ואת משך השהייה." },
      { question: "האם המחיר המוצג הוא המחיר הסופי?", answer: "זהו מחיר התחלה כאשר הוא מופיע. המחיר הסופי תלוי במשך השהייה, ביום, בשעה ובחדר שנבחר." },
      { question: "אפשר לבקש כניסה עצמאית?", answer: `אם ${placeName} מציע כניסה עצמאית, ההנחיות נמסרות לאחר האישור. כאשר האפשרות אינה מצוינת, הצוות בודק אותה מול המקום.` },
      { question: "מה כדאי לציין בבקשה?", answer: "יש לציין שעה רצויה, מספר שעות, מספר אורחים ובקשות מיוחדות. כך אפשר לקבל תשובה מדויקת ומהירה יותר." },
    ],
  };
}
