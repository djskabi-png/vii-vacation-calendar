export function getTrail(slug: string) {
  return trails.find((trail) => trail.slug === slug) || trails[0];
}

export function nearbyTrails(area: string, location: string, limit = 3) {
  const exact = trails.filter((trail) => trail.areaTags.some((tag) => area.includes(tag) || location.includes(tag)));
  const fallback = area.includes("צפון") || area.includes("גליל") || area.includes("כנרת")
    ? trails.filter((trail) => ["אצבע הגליל", "דרום רמת הגולן", "צפון הכנרת", "מרום הגליל"].includes(trail.region))
    : area.includes("ירושלים") || area.includes("ים המלח")
      ? trails.filter((trail) => ["מדבר יהודה", "צפון הנגב"].includes(trail.region))
      : area.includes("אילת") || area.includes("ערבה")
        ? trails.filter((trail) => trail.region === "הערבה התיכונה")
        : trails.filter((trail) => ["חוף הכרמל", "מזרח השרון", "עמק עכו"].includes(trail.region));
  return [...exact, ...fallback].filter((trail, index, all) => all.findIndex((item) => item.slug === trail.slug) === index).slice(0, limit);
}
