import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, relative, resolve } from "node:path";

const root = process.cwd();
const mediaRoot = resolve(root, "public/media");
const output = resolve(root, "app/lib/deployment-media-aliases.generated.ts");
const mediaExtensions = new Set([".avif", ".gif", ".jpeg", ".jpg", ".png", ".webp"]);

async function filesUnder(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesUnder(filename));
    else if (entry.isFile() && mediaExtensions.has(extname(entry.name).toLowerCase())) files.push(filename);
  }
  return files;
}

const groups = new Map();
for (const filename of await filesUnder(mediaRoot)) {
  const bytes = await readFile(filename);
  const hash = createHash("sha256").update(bytes).digest("hex");
  const publicPath = `/${relative(resolve(root, "public"), filename).replaceAll("\\", "/")}`;
  const group = groups.get(hash) || [];
  group.push(publicPath);
  groups.set(hash, group);
}

const aliases = {
  "/og.png": "/og-v2.png",
  "/vii-calendar-social.png": "/og-v2.png",
};

for (const paths of groups.values()) {
  if (paths.length < 2) continue;
  paths.sort((left, right) => left.length - right.length || left.localeCompare(right));
  const canonical = paths[0];
  for (const duplicate of paths.slice(1)) aliases[duplicate] = canonical;
}

const entries = Object.entries(aliases).sort(([left], [right]) => left.localeCompare(right));
const source = `// Generated by scripts/generate-deployment-media-aliases.mjs.\n` +
  `// Exact duplicate media keep their old URLs through Worker redirects.\n` +
  `export const deploymentMediaAliases: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, 2)});\n`;

await writeFile(output, source, "utf8");
console.log(`[deployment-media-aliases] generated ${entries.length} safe aliases`);
